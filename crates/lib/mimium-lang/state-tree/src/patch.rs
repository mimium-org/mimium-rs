/// A patch to be applied to a flat state storage from old storage.
///
/// A patch represents a flat array copy operation from the source data storage
/// to the destination data storage.
#[derive(Debug, PartialEq, Eq, Clone, Hash)]
pub struct CopyFromPatch {
    /// Starting address in the source data storage (index from the beginning of the array)
    pub src_addr: usize,
    /// Starting address in the destination data storage
    pub dst_addr: usize,
    /// Size of data to copy (in u64 units)
    pub size: usize,
}

/// Apply patches to a new flat array.
///
/// # Arguments
/// * `new_storage` - Destination flat array with the new structure (initialized with zeros)
/// * `old_storage` - Source flat array with the old structure
/// * `patches` - List of patches generated by the `diff` function
///
/// Parts of a patch outside either storage are skipped (see [`copy_clamped`]).
pub fn apply_patches(new_storage: &mut [u64], old_storage: &[u64], patches: &[CopyFromPatch]) {
    for patch in patches {
        copy_clamped(new_storage, old_storage, patch, 1);
    }
}

/// Copy one patch, scaled by `unit` elements per word, clamped to both buffers.
///
/// Storages are allowed to be shorter than their skeleton's `total_size()`: a runtime
/// may grow its storage lazily (e.g. the WASM backend only allocates delay buffers on
/// first use). The part of a patch that falls outside either buffer is skipped (the
/// destination keeps its initial value) instead of panicking on the audio thread.
pub fn copy_clamped<E: Copy>(new_storage: &mut [E], old_storage: &[E], patch: &CopyFromPatch, unit: usize) {
    let src = patch.src_addr * unit;
    let dst = patch.dst_addr * unit;
    let avail_src = old_storage.len().saturating_sub(src);
    let avail_dst = new_storage.len().saturating_sub(dst);
    let n = (patch.size * unit).min(avail_src).min(avail_dst);
    if n > 0 {
        new_storage[dst..dst + n].copy_from_slice(&old_storage[src..src + n]);
    }
}
